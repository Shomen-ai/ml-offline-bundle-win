-- Миграция для базы, где таблицы уже созданы (машина B).
-- На чистой базе ничего запускать не нужно: всё это уже есть в schema.sql.
--
-- Выполнять под тем же пользователем, под которым работает приложение.
-- Скрипт рассчитан на однократный запуск: повторный выдаст ORA-00955
-- (имя уже занято) и ORA-01430 (такая колонка уже есть) — это безопасно.

-- 1. Настройки LLM, которые правит админ-панель.
CREATE TABLE dpis_settings (
    skey VARCHAR2(64) PRIMARY KEY,
    sval CLOB
);

-- 2. Сводка диалога и граница, до которой она его покрывает.
--    Заполняются автоматически, когда история перестаёт влезать в контекст.
ALTER TABLE dpis_dialogs ADD (summary CLOB, summary_upto NUMBER);

-- 3. Если таблицы создавались ДО перехода на доменную авторизацию,
--    снимите NOT NULL с парольных колонок: у доменных учёток они пустые.
--    Если ограничений уже нет, Oracle ответит ORA-01451 — это нормально.
ALTER TABLE dpis_users MODIFY (password_hash NULL, salt NULL);

COMMIT;
